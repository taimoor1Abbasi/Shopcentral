-- Demo-only access: this exposes customer names and emails to unauthenticated visitors.
-- Replace these policies with authenticated, owner-scoped policies before production use.
create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  status text not null check (status in ('Active', 'Invited', 'Paused')),
  orders integer not null default 0 check (orders >= 0),
  spent numeric(10, 2) not null default 0 check (spent >= 0),
  joined date not null default current_date
);

alter table public.customers enable row level security;

drop policy if exists "Public can read demo customers" on public.customers;
create policy "Public can read demo customers"
  on public.customers for select to anon, authenticated
  using (true);

drop policy if exists "Public can add demo invitations" on public.customers;
create policy "Public can add demo invitations"
  on public.customers for insert to anon, authenticated
  with check (status = 'Invited' and orders = 0 and spent = 0);

grant select on public.customers to anon, authenticated;
grant insert (name, email, status, orders, spent, joined) on public.customers to anon, authenticated;
grant usage, select on sequence public.customers_id_seq to anon, authenticated;

